import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const catalog=JSON.parse(readFileSync(new URL('../js/exercise-catalog.json',import.meta.url)));
import {startingRoutine,ROUTINE_ID} from '../js/lift-routine.js';
import {exerciseDraft,safeMetrics,workoutSuggestion,rirText} from '../js/lift-domain.js';
import {validateLiftPlan,validateLiftSession} from '../supabase/functions/_shared/lift-schema.js';
let id=1;const uuid=()=>`b0000000-0000-4000-8000-${String(id++).padStart(12,'0')}`;
const plan={units:'lb',plates:[45,25,5,2.5],bar_weight:45,default_rest_seconds:120,version:0};
const p=startingRoutine(plan,uuid);validateLiftPlan(p);
assert.deepEqual(p.days.map(d=>d.name),['Push A','Pull A','Legs','Push B','Pull B']);
assert.throws(()=>startingRoutine(p),/already/);
assert.equal(p.days[0].exercises[0].details.references[2].weight,135);
const press=p.days[0].exercises[1];assert.equal(rirText(press.details.references[0]),'5+');assert.equal(press.details.references[1].rir,.5);
const draft=exerciseDraft(press,{plan:p,recent:{}},uuid);assert.equal(draft.source,'reference');assert.ok(draft.logged.every(s=>!s.completed));assert.equal(draft.logged[0].details.rir_qualifier,'at_least');assert.deepEqual(draft.last,[]);
const legs=p.days[2].exercises;assert.equal(legs[3].name,'Kettle SQ Extension');assert.equal(exerciseDraft(legs[0],{plan:p},uuid).logged[0].weight,null);
assert.equal(p.days[4].exercises.reduce((n,e)=>n+e.sets,0),23);
const weighted=exerciseDraft(p.days[0].exercises[5],{plan:p},uuid);assert.equal(weighted.logged[0].weight,25);assert.equal(weighted.logged[0].details.load_type,'added');
assert.equal(safeMetrics(weighted.logged.map(s=>({...s,completed:true}))).volume,0);assert.equal(safeMetrics(weighted.logged.map(s=>({...s,completed:true}))).e1rm,null);
const history=[{units:'lb',sets:[{weight:100,reps:12,rir:2,is_warmup:false,details:{load_type:'external',apparatus:''}}]}];
const ex={...press,sets:1,details:{...press.details,apparatus:''}};assert.equal(workoutSuggestion(ex,history).source,'confirmed');assert.equal(workoutSuggestion(ex,history).sets[0].weight,105);
assert.equal(workoutSuggestion({...ex,details:{...ex.details,load_type:'assisted'}},history).source,'reference','incomparable load types are excluded');
const set={exercise_id:press.id,exercise_name:press.name,exercise_notes:'',set_no:1,is_warmup:false,weight:135,reps:11,rir:5,details:{rir_qualifier:'at_least'}};
const session={id:uuid(),lift_day_id:p.days[0].id,day_name:'Push A',units:'lb',started_at:new Date().toISOString(),finished_at:new Date().toISOString(),notes:'',sets:[set]};
assert.equal(validateLiftSession(session,'UTC').sets[0].details.rir_qualifier,'at_least');
assert.throws(()=>validateLiftSession({...session,sets:[{...set,details:{load_type:'bodyweight'},weight:25}]},'UTC'));
console.log('ok  Five-day reference import, repeat prevention, exact set values, fractional/qualified RIR, unset loads and confirmed progression');
const {loadType}=await import('../js/lift-domain.js');assert.equal(loadType({equipment:'bodyweight',logged:[{weight:25,completed:true}]}),'unknown','old draft load semantics stay unverified; values are not erased or treated as total bodyweight');
const qualified=workoutSuggestion({...ex,sets:3},[{units:'lb',sets:[{weight:135,reps:11,rir:5,details:{load_type:'external',apparatus:'',rir_qualifier:'at_least'}},{weight:185,reps:12,rir:.5,details:{load_type:'external',apparatus:''}}]}]);
assert.deepEqual(qualified.sets.map(s=>s.weight),[135,185,185],'qualified set is not removed or shifted into a different set');assert.equal(qualified.sets[0].details.rir_qualifier,'at_least');assert.equal(qualified.last.length,2);

const {routineIdFor,SUE_ROUTINE_ID,routineFlagsFor}=await import('../js/lift-routine.js');
const sue=startingRoutine(plan,uuid,'sue',catalog);validateLiftPlan(sue);
assert.equal(routineIdFor('sue'),SUE_ROUTINE_ID);
assert.equal(sue.details.imports.includes(SUE_ROUTINE_ID),true);
assert.equal(sue.details.imports.includes(ROUTINE_ID),false);
assert.deepEqual(sue.days.map(d=>d.name),['Lower A · Glutes + quads','Upper A · Push + pull','Lower B · Glutes + hamstrings','Upper B · Back + shoulders','Lower C · Glutes + legs']);
assert.equal(sue.days.filter(d=>d.name.startsWith('Lower')).length,3);
assert.equal(sue.days.filter(d=>d.name.startsWith('Upper')).length,2);
assert.equal(sue.details.preferences.priorities.glutes,'high');
assert.equal(sue.details.preferences.split,'lower-upper');
assert.ok(sue.days.flatMap(d=>d.exercises).every(e=>e.details.references.length===0&&e.details.source===SUE_ROUTINE_ID));
for(const e of sue.days.flatMap(d=>d.exercises)){
 const suggested=exerciseDraft(e,{plan:sue,recent:{}},uuid);
 assert.equal(suggested.source,'target');assert.deepEqual(suggested.last,[]);
 assert.ok(suggested.logged.every(s=>!s.completed));
 assert.ok(suggested.logged.every(s=>s.weight===(e.details.load_type==='bodyweight'?0:null)));
}
assert.throws(()=>startingRoutine(sue,uuid,'sue',catalog),/already/);
assert.equal(press.details.references[0].weight,135,'Carlos starting values were not mutated');
assert.ok(routineFlagsFor('sue').some(s=>s.includes('No weights, reps or RIR from Carlos')));
assert.ok(!JSON.stringify(sue).includes('June 28'),'Sue’s template does not inherit Carlos’s dated performance labels');
assert.throws(()=>routineIdFor('unknown'),/Unknown/);
console.log('ok  Sue has her own repeat-safe template, no copied performance or assumed loads, and independent unchecked drafts');

const {muscleWork}=await import('../js/lift-generator.js');
const sueWork=muscleWork(sue.days.flatMap(d=>d.exercises));
assert.equal(sueWork.glutes.direct,6);assert.equal(sueWork.quadriceps.direct,6);assert.equal(sueWork.hamstrings.direct,6);
assert.ok(Object.values(sueWork).every(m=>m.direct+m.indirect<=14),'template stays within the default combined-set planning cap');
assert.ok(sue.days.flatMap(d=>d.exercises).every(e=>e.details.catalog_id&&e.target_rir===3));
const legacySue={...plan,details:{imports:['sue-five-session-v1']}};
const revisedSue=startingRoutine(legacySue,uuid,'sue',catalog);
assert.deepEqual(legacySue.details.imports,['sue-five-session-v1'],'previously loaded Sue plan is not rewritten automatically');
assert.ok(revisedSue.details.imports.includes('sue-five-session-v1')&&revisedSue.details.imports.includes(SUE_ROUTINE_ID));
assert.throws(()=>startingRoutine(plan,uuid,'sue',[]),/missing/);
console.log('ok  Sue glute/leg emphasis: three lower/two upper sessions, pinned exercise mappings, bounded work and explicit opt-in upgrade');
