import assert from 'node:assert/strict';
import { suggest, roundIncrement, plateMath, e1RM, volume, warmups, convertWeight } from '../js/lift-rules.js';
const ex = { sets: 3, rep_min: 8, rep_max: 12, target_rir: 2, increment: 5, equipment: 'barbell' };
const history = (reps, rir = 2, weight = 100, units = 'lb') => ({ units, sets: reps.map((reps) => ({ weight, reps, rir })) });
assert.equal(suggest(ex).branch, 'first');
const up = suggest(ex, [history([12, 12, 12])]);
assert.deepEqual(up.sets[0], { weight: 105, reps: 8, rir: 2 });
assert.notEqual(suggest(ex, [history([12, 12, 12], 1)]).branch, 'increase');
assert.deepEqual(suggest(ex, [history([10, 8, 8])]).sets.map((s) => s.reps), [10, 9, 9]);
assert.equal(suggest(ex, [history([10, 7, 8])]).branch, 'hold');
assert.equal(suggest(ex, [history([7, 8, 8]), history([8, 8, 8])]).branch, 'hold');
const down = suggest(ex, [history([7, 8, 8]), history([8, 7, 8])]);
assert.equal(down.branch, 'deload');
assert.equal(down.sets[0].weight, 90);
assert.equal(suggest(ex, [history([12, 12])]).branch, 'hold');
const withWarmups = history([12, 12, 12]);
withWarmups.sets.unshift({ weight: 45, reps: 2, rir: 0, is_warmup: true });
assert.equal(suggest(ex, [withWarmups]).branch, 'increase');
assert.equal(roundIncrement(101, 2.5), 100);
assert.equal(roundIncrement(94.5, 5, 'down'), 90);
assert.equal(roundIncrement(0.3, 0.1, 'down'), 0.3);
assert.throws(() => roundIncrement(5, 0));
assert.equal(suggest({ ...ex, increment: 2.5 }, [history([12, 12, 12], 2, 50, 'kg')], 'kg').sets[0].weight, 52.5);
assert.ok(Math.abs(convertWeight(convertWeight(100, 'lb', 'kg'), 'kg', 'lb') - 100) < 0.00001);
assert.equal(plateMath(225, 45, [45, 35, 25, 10, 5, 2.5]).actual, 225);
assert.deepEqual(plateMath(225, 45, [45, 35, 25, 10, 5, 2.5]).plates, [45, 45]);
assert.equal(plateMath(101, 45, [25, 10, 5, 2.5]).leftover, 1);
assert.deepEqual(plateMath(32, 20, [5, 3]).plates, [3, 3]);
assert.equal(plateMath(62.5, 20, [20, 10, 5, 2.5, 1.25]).actual, 62.5);
assert.equal(plateMath(10, 45, [45]).belowBar, true);
assert.equal(e1RM(100, 10, 2), 140);
assert.equal(e1RM(0, 10, 2), 0);
assert.equal(e1RM(100, 0, 0), 0);
assert.equal(volume([{ weight: 100, reps: 10 }, { weight: 45, reps: 8, is_warmup: true }]), 1000);
assert.deepEqual(warmups(100, ex, { bar_weight: 45, plates: [45, 25, 10, 5, 2.5] }).map((s) => s.weight), [50, 70, 85]);
console.log('ok  Lift progression, deloads, units, plate combinations, warm-ups and e1RM');
